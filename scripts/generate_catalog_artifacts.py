def rust_encoding_variant(value: str) -> str:
    if value == "object":
        return "Object"
    if value == "array":
        return "Array"
    if value == "base64-le":
        return "Base64Le"
    raise ValueError(f"unsupported encoding: {value}")


def rust_identifier(value: str) -> str:
    pieces: list[str] = []
    for char in value:
        if char.isascii() and (char.isalnum() or char == "_"):
            pieces.append(char)
        else:
            pieces.append("_")
    rendered = "".join(pieces)
    if not rendered:
        return "_"
    if rendered[0].isdigit():
        return f"_{rendered}"
    return rendered


def scalar_storage_name(type_id: str) -> str:
    return type_id.rsplit("_", maxsplit=1)[1]


def conversion_kind_variant(kind: str) -> str:
    if kind == "linear":
        return "Linear"
    if kind == "affine":
        return "Affine"
    raise ValueError(f"unsupported conversion kind: {kind}")


def conversion_offset_literal(offset_to_base: float | None) -> str:
    if offset_to_base is None:
        return "None"
    return f"Some({offset_to_base!r})"


def render_generated_ffi_types(summary: dict) -> str:
    dimensions = summary["dimensions"]
    exemplar_dimension = next(dimension for dimension in dimensions if dimension["dimension_id"] == "distance")
    exemplar_unit = next(unit for unit in exemplar_dimension["units"] if unit["unit_code_id"] == "mm")
    scalar_type_id = next(value for value in exemplar_dimension["scalar"]["type_ids"] if value.endswith("_i32"))
    storage = scalar_type_id.rsplit("_", maxsplit=1)[1]
    abi_name_stem = exemplar_dimension["abi_name_stem"]
    unit_code_id = exemplar_unit["unit_code_id"]
    type_name = rust_identifier(f"{abi_name_stem}_{unit_code_id}_{storage}")
    field_name = rust_identifier(f"value_{unit_code_id}")
    slice_name = rust_identifier(f"{type_name}_slice")
    slice_mut_name = rust_identifier(f"{type_name}_slice_mut")

    lines = [
        "// @generated by scripts/generate_catalog_artifacts.py",
        "#![allow(non_camel_case_types)]",
        "",
    ]
    lines.extend(
        [
            "/// ABI-facing scalar name pattern generated from catalog naming metadata.",
            "#[repr(C)]",
            "#[derive(Copy, Clone, Debug, PartialEq, Eq)]",
            f"pub struct {type_name} {{",
            f"    pub {field_name}: i32,",
            "}",
            "",
            "/// ABI slice pattern generated from catalog naming metadata.",
            "#[repr(C)]",
            "#[derive(Copy, Clone, Debug)]",
            f"pub struct {slice_name} {{",
            f"    pub ptr: *const {type_name},",
            "    pub len: u64,",
            "}",
            "",
            f"impl {slice_name} {{",
            "    pub const fn is_contract_valid(self) -> bool {",
            "        self.ptr.is_null() == (self.len == 0)",
            "    }",
            "}",
            "",
            "/// Mutable ABI slice pattern generated from catalog naming metadata.",
            "#[repr(C)]",
            "#[derive(Copy, Clone, Debug)]",
            f"pub struct {slice_mut_name} {{",
            f"    pub ptr: *mut {type_name},",
            "    pub len: u64,",
            "}",
            "",
            f"impl {slice_mut_name} {{",
            "    pub const fn is_contract_valid(self) -> bool {",
            "        self.ptr.is_null() == (self.len == 0)",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines) + "\n"


